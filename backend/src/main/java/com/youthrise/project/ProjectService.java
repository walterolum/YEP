package com.youthrise.project;

import com.youthrise.common.ApiException;
import com.youthrise.notification.NotificationKind;
import com.youthrise.notification.NotificationService;
import com.youthrise.user.Role;
import com.youthrise.user.User;
import com.youthrise.user.UserPrincipal;
import com.youthrise.user.UserRepository;
import java.util.List;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.multipart.MultipartFile;

@Service
public class ProjectService {

    private final ProjectRepository projects;
    private final MilestoneRepository milestones;
    private final SubmissionRepository submissions;
    private final TeamService teams;
    private final UserRepository users;
    private final EvidenceStorage storage;
    private final NotificationService notifications;

    public ProjectService(ProjectRepository projects, MilestoneRepository milestones,
                          SubmissionRepository submissions, TeamService teams,
                          UserRepository users, EvidenceStorage storage, NotificationService notifications) {
        this.projects = projects;
        this.milestones = milestones;
        this.submissions = submissions;
        this.teams = teams;
        this.users = users;
        this.storage = storage;
        this.notifications = notifications;
    }

    @Transactional(readOnly = true)
    public ProjectDtos.ProjectResponse getByTeam(String teamId, UserPrincipal principal) {
        teams.requireAccessible(teamId, principal);
        return ProjectDtos.ProjectResponse.from(projectFor(teamId));
    }

    /**
     * Creates the single Impact Project owned by a Level Two team. The first
     * milestone list is generated by the programme template, so this method only
     * captures the team's own framing of the problem.
     */
    @Transactional
    public ProjectDtos.ProjectResponse createProject(String teamId, ProjectDtos.CreateProjectRequest request,
                                                     UserPrincipal principal) {
        Team team = teams.requireAccessible(teamId, principal);
        requireMember(team, principal);
        if (projects.findByTeamId(teamId).isPresent()) {
            throw ApiException.conflict("PROJECT_EXISTS",
                    "This team already has an Impact Project.");
        }
        List<String> objectives = request.objectives() == null ? List.of() : request.objectives();
        Project project = Project.create(team, request.title(), request.problem(), request.theme(),
                request.summary(), ProjectStatus.DRAFT, objectives);
        projects.save(project);
        notifyTeam(team, "Impact Project created",
                "\"" + project.getTitle() + "\" is ready. Start the first milestone.",
                NotificationKind.ANNOUNCEMENT);
        return ProjectDtos.ProjectResponse.from(project);
    }

    @Transactional
    public ProjectDtos.ProjectResponse startMilestone(String teamId, String milestoneId,
                                                      MilestoneStatus status, UserPrincipal principal) {
        Team team = teams.requireAccessible(teamId, principal);
        requireMember(team, principal);
        if (status != MilestoneStatus.IN_PROGRESS) {
            throw ApiException.validation("status",
                    "Use the evidence submission and review workflow to change this milestone.");
        }
        Project project = projectFor(teamId);
        Milestone milestone = requiredMilestone(milestoneId, project);
        try {
            milestone.startWork();
        } catch (IllegalStateException ex) {
            throw ApiException.conflict("MILESTONE_LOCKED",
                    "This milestone is already submitted for review or approved.");
        }
        return ProjectDtos.ProjectResponse.from(project);
    }

    @Transactional
    public ProjectDtos.SubmissionResponse submitEvidence(String teamId, String milestoneId, String note,
                                                         MultipartFile file, UserPrincipal principal) {
        Team team = teams.requireAccessible(teamId, principal);
        requireMember(team, principal);
        Project project = projectFor(teamId);
        Milestone milestone = requiredMilestone(milestoneId, project);
        if (milestone.getStatus() == MilestoneStatus.APPROVED) {
            throw ApiException.conflict("MILESTONE_APPROVED",
                    "This milestone has already been approved. Submit evidence for the next milestone.");
        }
        if (file == null || file.isEmpty()) {
            throw ApiException.validation("file", "Attach a file before submitting evidence.");
        }

        String originalName = EvidenceStorage.safeFileName(file.getOriginalFilename());
        String storedName = storage.store(file);
        User submitter = users.findById(principal.id())
                .orElseThrow(() -> ApiException.notFound("USER_NOT_FOUND", "That account could not be found."));

        Submission submission = Submission.create(project, team, milestone, milestone.getTitle(),
                originalName, storedName, file.getContentType(), file.getSize(), note, submitter);
        milestone.markSubmitted(originalName);
        submissions.save(submission);
        notifyTeam(team, "Evidence submitted",
                "\"" + milestone.getTitle() + "\" was submitted for review.", NotificationKind.APPROVAL);
        return ProjectDtos.SubmissionResponse.from(submission);
    }

    @Transactional
    public void review(String submissionId, ProjectDtos.ReviewRequest request, UserPrincipal principal) {
        Submission submission = submissions.findById(submissionId)
                .orElseThrow(() -> ApiException.notFound("SUBMISSION_NOT_FOUND",
                        "That submission could not be found."));
        Team team = submission.getTeam();
        if (!teams.canManage(team, principal)) {
            throw ApiException.forbidden("REVIEW_NOT_ALLOWED",
                    "Only the assigned mentor, programme facilitator or an administrator can review this work.");
        }
        if (submission.getStatus() != SubmissionStatus.SUBMITTED
                && submission.getStatus() != SubmissionStatus.UNDER_REVIEW) {
            throw ApiException.conflict("SUBMISSION_ALREADY_REVIEWED",
                    "This submission has already been reviewed.");
        }
        if (request.status() != SubmissionStatus.APPROVED && request.status() != SubmissionStatus.REVISION) {
            throw ApiException.validation("status", "Choose approval or a revision request.");
        }
        if (request.status() == SubmissionStatus.APPROVED && request.score() == null) {
            throw ApiException.validation("score", "Enter a score before approving this milestone.");
        }

        User reviewer = users.findById(principal.id())
                .orElseThrow(() -> ApiException.notFound("USER_NOT_FOUND", "That account could not be found."));
        submission.review(reviewer, request.status(), request.score(), request.feedback());
        Milestone milestone = submission.getMilestone();
        if (request.status() == SubmissionStatus.APPROVED) {
            milestone.approve(request.feedback());
            notifyTeam(team, "Milestone approved",
                    "\"" + milestone.getTitle() + "\" was approved.", NotificationKind.APPROVAL);
        } else {
            milestone.requestRevision(request.feedback());
            notifyTeam(team, "Revision requested",
                    "\"" + milestone.getTitle() + "\" needs changes before it can be approved.",
                    NotificationKind.FEEDBACK);
        }
    }

    @Transactional(readOnly = true)
    public List<ProjectDtos.SubmissionResponse> listForMentor(String mentorId) {
        return submissions.findByTeamMentorIdOrderBySubmittedAtDesc(mentorId).stream()
                .map(ProjectDtos.SubmissionResponse::from)
                .toList();
    }

    private Project projectFor(String teamId) {
        return projects.findByTeamId(teamId)
                .orElseThrow(() -> ApiException.notFound("PROJECT_NOT_FOUND",
                        "No project is linked to this team yet."));
    }

    private Milestone requiredMilestone(String milestoneId, Project project) {
        return milestones.findByIdAndProjectId(milestoneId, project.getId())
                .orElseThrow(() -> ApiException.notFound("MILESTONE_NOT_FOUND",
                        "That milestone does not belong to this team's project."));
    }

    private static void requireMember(Team team, UserPrincipal principal) {
        if (principal.role() != Role.PARTICIPANT || !team.hasMember(principal.id())) {
            throw ApiException.forbidden("TEAM_MEMBER_REQUIRED",
                    "Only members of this team can change its project work.");
        }
    }

    private void notifyTeam(Team team, String title, String body, NotificationKind kind) {
        for (User member : team.getMembers()) {
            notifications.notifyUser(member, title, body, "/app/projects", kind);
        }
    }
}
